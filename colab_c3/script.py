# Модульная строка документации с кратким описанием назначения скрипта.
"""Полный перебор NxN масок для test_c3.jpg."""

# Импорт аннотаций из будущих версий Python для отложенной оценки типов.
from __future__ import annotations

# Импорт класса Path для работы с путями файловой системы.
from pathlib import Path

# Пустая строка, отделяющая стандартную библиотеку от сторонних зависимостей.

# Импорт классов Image и ImageDraw из библиотеки Pillow для работы с изображениями.
from PIL import Image, ImageDraw

# Пустая строка перед блоком объявления констант и путей.

# Пояснение к константе N: размер ячейки сетки на изображении.
# Размер ячейки сетки (определён анализом розовых квадратов на test_c3.jpg:
# наибольшая доля однородных NxN-блоков и шаг смены цвета ≈ 2 пикселя).
# Константа N — сторона квадрата сегментирующей маски в пикселях.
N = 2

# Пустая строка после объявления константы N.

# Абсолютный путь к каталогу, в котором расположен текущий скрипт.
SCRIPT_DIR = Path(__file__).resolve().parent
# Путь к исходному изображению test_c3.jpg в родительском каталоге.
IMAGE_PATH = SCRIPT_DIR.parent / "test_c3.jpg"
# Путь к каталогу result для сохранения сгенерированных масок.
RESULT_DIR = SCRIPT_DIR / "result"

# Пустая строка перед определением главной функции.


# Объявление главной функции, координирующей все шаги обработки.
def main() -> None:
    # Вложенная функция первого шага: загрузка изображения в память.
    def step_1_load_image() -> Image.Image:
        # Открытие файла изображения и преобразование в RGB-формат.
        image = Image.open(IMAGE_PATH).convert("RGB")
        # Получение ширины и высоты загруженного изображения.
        width, height = image.size
        # Формирование словаря с метаданными загруженного изображения.
        result = {
            # Строковое представление пути к файлу изображения.
            "path": str(IMAGE_PATH),
            # Ширина изображения в пикселях.
            "width": width,
            # Высота изображения в пикселях.
            "height": height,
            # Цветовой режим изображения (RGB).
            "mode": image.mode,
        }
        # Вывод результата шага 1 в стандартный поток вывода.
        print(f"step_1: {result}")
        # Возврат объекта изображения вызывающему коду.
        return image

    # Вложенная функция второго шага: проверка размера сетки N.
    def step_2_verify_grid_size(image: Image.Image) -> int:
        # Получение прямого доступа к пикселям изображения.
        pixels = image.load()
        # Чтение ширины и высоты переданного изображения.
        width, height = image.size
        # Инициализация лучшего кандидата значением заданной константы N.
        best_n = N
        # Инициализация наилучшей доли однородных блоков нулём.
        best_ratio = 0.0

        # Пустая строка перед циклом перебора кандидатов размера сетки.

        # Перебор возможных размеров ячейки от 2 до 6 пикселей.
        for candidate in range(2, 7):
            # Счётчик однородных блоков для текущего кандидата.
            uniform = 0
            # Счётчик всех проверенных блоков для текущего кандидата.
            total = 0
            # Внешний цикл по вертикали с шагом, равным размеру кандидата.
            for y in range(0, height - candidate + 1, candidate):
                # Внутренний цикл по горизонтали с шагом, равным размеру кандидата.
                for x in range(0, width - candidate + 1, candidate):
                    # Увеличение общего числа проверенных блоков на единицу.
                    total += 1
                    # Эталонный цвет левого верхнего пикселя текущего блока.
                    base = pixels[x, y]
                    # Проверка однородности всех пикселей внутри блока candidate×candidate.
                    if all(
                        # Сумма абсолютных отклонений по каналам R, G, B от эталона.
                        sum(abs(pixels[x + dx, y + dy][channel] - base[channel]) for channel in range(3))
                        # Допустимый порог отклонения цвета для признания пикселя однородным.
                        <= 15
                        # Перебор строк внутри блока.
                        for dy in range(candidate)
                        # Перебор столбцов внутри блока.
                        for dx in range(candidate)
                    # Конец условия проверки однородности блока.
                    ):
                        # Увеличение счётчика однородных блоков при успешной проверке.
                        uniform += 1
            # Вычисление доли однородных блоков для текущего кандидата.
            ratio = uniform / total if total else 0.0
            # Сравнение доли с наилучшим найденным значением.
            if ratio > best_ratio:
                # Обновление наилучшей доли однородных блоков.
                best_ratio = ratio
                # Запоминание размера ячейки с наилучшей долей однородности.
                best_n = candidate

        # Формирование словаря с результатами проверки размера сетки.
        result = {
            # Значение N, заданное константой в начале скрипта.
            "configured_n": N,
            # Размер ячейки, автоматически определённый по однородности блоков.
            "detected_n": best_n,
            # Доля однородных блоков для лучшего кандидата, округлённая до 4 знаков.
            "uniform_block_ratio": round(best_ratio, 4),
            # Флаг совпадения заданного и определённого значений N.
            "match": N == best_n,
        }
        # Вывод результата шага 2 в стандартный поток вывода.
        print(f"step_2: {result}")
        # Возврат константы N как подтверждённого размера ячейки.
        return N

    # Вложенная функция третьего шага: подготовка каталога для масок.
    def step_3_prepare_result_dir() -> Path:
        # Создание каталога result, включая все промежуточные родительские каталоги.
        RESULT_DIR.mkdir(parents=True, exist_ok=True)
        # Формирование словаря с информацией о каталоге результатов.
        result = {
            # Строковое представление пути к каталогу result.
            "result_dir": str(RESULT_DIR),
            # Проверка, что каталог result существует на диске.
            "exists": RESULT_DIR.is_dir(),
        }
        # Вывод результата шага 3 в стандартный поток вывода.
        print(f"step_3: {result}")
        # Возврат объекта Path каталога результатов.
        return RESULT_DIR

    # Вложенная функция четвёртого шага: полный перебор и сохранение масок.
    def step_4_enumerate_masks(
        # Исходное изображение, размер которого определяет размер каждой маски.
        image: Image.Image,
        # Сторона квадрата N для сегментирующей маски.
        square_size: int,
        # Каталог, в который сохраняются файлы масок.
        output_dir: Path,
    # Аннотация возвращаемого типа: словарь со статистикой генерации масок.
    ) -> dict[str, int | str]:
        # Получение ширины и высоты исходного изображения.
        width, height = image.size
        # Число возможных горизонтальных позиций окна N×N (полный перебор).
        positions_x = width - square_size + 1
        # Число возможных вертикальных позиций окна N×N (полный перебор).
        positions_y = height - square_size + 1
        # Общее ожидаемое количество масок как произведение позиций.
        total_masks = positions_x * positions_y
        # Счётчик фактически сохранённых на диск масок.
        saved = 0

        # Пустая строка перед двойным циклом перебора позиций маски.

        # Внешний цикл: перебор всех вертикальных координат верхнего левого угла.
        for top in range(positions_y):
            # Внутренний цикл: перебор всех горизонтальных координат верхнего левого угла.
            for left in range(positions_x):
                # Создание чёрной маски в градациях серого того же размера, что и изображение.
                mask = Image.new("L", (width, height), 0)
                # Получение объекта для рисования на маске.
                draw = ImageDraw.Draw(mask)
                # Отрисовка белого прямоугольника N×N в текущей позиции окна.
                draw.rectangle(
                    # Координаты противоположных углов прямоугольника (включительно).
                    (left, top, left + square_size - 1, top + square_size - 1),
                    # Заливка прямоугольника белым цветом (значение 255).
                    fill=255,
                )
                # Формирование имени файла маски по координатам окна.
                filename = f"mask_x{left:04d}_y{top:04d}.png"
                # Сохранение маски в каталог результатов под сформированным именем.
                mask.save(output_dir / filename)
                # Увеличение счётчика сохранённых масок на единицу.
                saved += 1

        # Формирование словаря с итоговой статистикой генерации масок.
        result = {
            # Использованный размер стороны квадрата маски.
            "square_size": square_size,
            # Количество горизонтальных позиций перебора.
            "positions_horizontal": positions_x,
            # Количество вертикальных позиций перебора.
            "positions_vertical": positions_y,
            # Фактическое число сохранённых масок.
            "total_masks_saved": saved,
            # Ожидаемое число масок по формуле перебора.
            "expected_masks": total_masks,
            # Строковый путь к каталогу с результатами.
            "output_dir": str(output_dir),
        }
        # Вывод результата шага 4 в стандартный поток вывода.
        print(f"step_4: {result}")
        # Возврат словаря со статистикой генерации масок.
        return result

    # Вызов шага 1: загрузка изображения в память.
    image = step_1_load_image()
    # Вызов шага 2: проверка и подтверждение размера сетки N.
    square_size = step_2_verify_grid_size(image)
    # Вызов шага 3: создание каталога для сохранения масок.
    output_dir = step_3_prepare_result_dir()
    # Вызов шага 4: полный перебор позиций и сохранение всех масок.
    step_4_enumerate_masks(image, square_size, output_dir)

# Пустая строка перед точкой входа при запуске скрипта как программы.


# Условие: скрипт запущен напрямую, а не импортирован как модуль.
if __name__ == "__main__":
    # Запуск главной функции обработки изображения.
    main()
