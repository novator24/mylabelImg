# Описание назначения модуля: сопоставление текста с вопросом о наличии элемента Ca
"""Сопоставление строк test_b2.txt с вопросом: содержит ли строка элемент Ca."""

# Подключение отложенной оценки аннотаций типов для совместимости с Python 3.7+
from __future__ import annotations

# Импорт модуля регулярных выражений для разбора ответов модели
import re
# Импорт счётчика для подсчёта голосов YES/NO при majority vote
from collections import Counter
# Импорт Path для работы с путями к файлам и каталогам
from pathlib import Path

# Импорт HTTP-клиента для обращения к REST API Ollama
import requests

# Имя локальной модели Ollama (qwen2.5-coder, 7B)
MODEL_NAME = "qwen2.5-coder:7b"
# URL эндпоинта чата Ollama на локальном хосте
OLLAMA_URL = "http://localhost:11434/api/chat"
# Количество повторных запусков модели на одну строку для голосования
NUM_RUNS = 20
# Температура генерации: умеренная случайность для разнообразия ответов
TEMPERATURE = 0.3
# Таймаут HTTP-запроса к Ollama в секундах
REQUEST_TIMEOUT = 120


# Главная точка входа: оркестрация всех шагов обработки
def main() -> None:
    # Корневая директория проекта (родитель каталога colab_b2)
    root_dir = Path(__file__).resolve().parent.parent
    # Путь к входному файлу со строками для классификации
    input_path = root_dir / "test_b2.txt"
    # Путь к каталогу для сохранения результатов YES/NO
    result_dir = root_dir / "result"

    # Шаг 1: загрузка строк из test_b2.txt в память
    def step_1_load_lines() -> list[str]:
        # Документация вложенной функции шага 1
        """Загрузить test_b2.txt в память."""
        # Чтение файла в UTF-8 и разбиение на список строк без переводов строк
        lines = input_path.read_text(encoding="utf-8").splitlines()
        # Вывод количества загруженных строк и пути к файлу
        print(f"step_1: загружено {len(lines)} строк из {input_path}")
        # Возврат списка строк вызывающему коду
        return lines

    # Шаг 2: подготовка каталога result для записи ответов
    def step_2_prepare_dirs() -> Path:
        # Документация вложенной функции шага 2
        """Подготовить каталог result."""
        # Создание каталога result, если его ещё нет (включая родительские)
        result_dir.mkdir(parents=True, exist_ok=True)
        # Сообщение о готовности каталога результатов
        print(f"step_2: каталог результатов готов — {result_dir}")
        # Возврат пути к каталогу результатов
        return result_dir

    # Шаг 3: формирование system/user промпта для одной строки
    def step_3_build_prompt(line_text: str) -> list[dict[str, str]]:
        # Документация вложенной функции шага 3
        """Сформировать улучшенный промпт для классификации Ca."""
        # Системный промпт с правилами классификации кальция (Ca)
        system_prompt = (
            # Роль модели: эксперт по минералогии и геохимии
            "Ты эксперт по минералогии и геохимии. "
            # Основная задача: определить отнесённость строки к элементу Ca
            "Твоя единственная задача — определить, относится ли строка к кальцию (химический элемент Ca, кальций).\n\n"
            # Требование отвечать только YES или NO
            "Отвечай строго одним словом: YES или NO.\n\n"
            # Заголовок блока правил для ответа YES
            "Правила YES:\n"
            # YES: явное присутствие подстроки Ca в названии
            "- в строке явно есть подстрока 'Ca' как символ элемента (например: REE-Ca-Si-P, Fe-Ti-Ca-oxides);\n"
            # YES: минерал или группа с характерным содержанием кальция
            "- строка называет минерал или группу, где кальций — обязательный или характерный компонент "
            # Примеры минералов с кальцием
            "(например: Calcite, Apatite, Dolomite).\n\n"
            # Заголовок блока правил для ответа NO
            "Правила NO:\n"
            # NO: числа, единицы, техника без упоминания Ca
            "- строка — только число, единица измерения, техника анализа или общая подпись без Ca "
            # Примеры строк без кальция
            "(например: 0.21, area%, 200 um, BSE, Quartz, Feldspars);\n"
            # NO: нет Ca и нет типичных Ca-минералов
            "- в строке нет 'Ca' и нет минерала/группы, для которых кальций типичен.\n\n"
            # Запрет пояснений; формат ответа строго YES или NO
            "Не добавляй пояснений. Формат ответа: YES или NO."
        )
        # Пользовательский промпт с конкретной строкой для анализа
        user_prompt = (
            # Заголовок блока с анализируемой строкой
            f"Строка для анализа:\n"
            # Текст строки в кавычках для однозначности
            f"\"{line_text}\"\n\n"
            # Формулировка вопроса о наличии элемента Ca
            f"Вопрос: содержит ли эта строка элемент Ca (кальций) — явно или через минерал/группу с Ca?\n"
            # Указание формата ответа
            f"Ответ (только YES или NO):"
        )
        # Список сообщений для API чата: system + user
        messages = [
            # Системное сообщение с правилами классификации
            {"role": "system", "content": system_prompt},
            # Пользовательское сообщение с текстом строки и вопросом
            {"role": "user", "content": user_prompt},
        ]
        # Возврат готового списка сообщений для Ollama
        return messages

    # Шаг 4: нормализация сырого ответа модели к YES или NO
    def step_4_parse_answer(raw: str) -> str:
        # Документация вложенной функции шага 4
        """Извлечь YES/NO из ответа модели."""
        # Приведение ответа к верхнему регистру и удаление пробелов по краям
        text = raw.strip().upper()
        # Поиск английского YES как отдельного слова
        if re.search(r"\bYES\b", text):
            # Возврат положительного ответа
            return "YES"
        # Поиск английского NO как отдельного слова
        if re.search(r"\bNO\b", text):
            # Возврат отрицательного ответа
            return "NO"
        # Распознавание русского «ДА» или сокращения Y как YES
        if "ДА" in text or text == "Y":
            # Возврат YES при русскоязычном или сокращённом ответе
            return "YES"
        # Распознавание русского «НЕТ» или сокращения N как NO
        if "НЕТ" in text or text == "N":
            # Возврат NO при русскоязычном или сокращённом ответе
            return "NO"
        # Значение по умолчанию при нераспознанном ответе — NO
        return "NO"

    # Шаг 5: один HTTP-запрос к локальной модели Ollama
    def step_5_query_ollama(messages: list[dict[str, str]]) -> str:
        # Документация вложенной функции шага 5
        """Один запрос к локальной модели Ollama через REST API."""
        # POST-запрос к эндпоинту /api/chat Ollama
        response = requests.post(
            # URL сервера Ollama
            OLLAMA_URL,
            # Тело запроса: модель, сообщения, параметры генерации
            json={
                # Имя используемой модели
                "model": MODEL_NAME,
                # История сообщений (system + user)
                "messages": messages,
                # Отключение потоковой передачи — один полный ответ
                "stream": False,
                # Параметры сэмплирования модели
                "options": {"temperature": TEMPERATURE},
            },
            # Максимальное время ожидания ответа сервера
            timeout=REQUEST_TIMEOUT,
        )
        # Проверка HTTP-статуса; исключение при ошибке 4xx/5xx
        response.raise_for_status()
        # Извлечение текста ответа ассистента из JSON
        content = response.json()["message"]["content"]
        # Парсинг YES/NO и возврат нормализованного ответа
        return step_4_parse_answer(content)

    # Шаг 6: голосование по 20 запускам для одной строки
    def step_6_majority_vote(line_text: str, line_index: int) -> tuple[str, Counter[str]]:
        # Документация вложенной функции шага 6
        """20 запусков подряд; итог — самый частый ответ."""
        # Построение промпта для текущей строки
        messages = step_3_build_prompt(line_text)
        # Список ответов за все запуски
        votes: list[str] = []
        # Цикл из NUM_RUNS (20) последовательных обращений к модели
        for run in range(1, NUM_RUNS + 1):
            # Один запрос к Ollama и получение YES или NO
            answer = step_5_query_ollama(messages)
            # Добавление ответа в список голосов
            votes.append(answer)
            # Логирование номера строки, запуска и ответа
            print(f"  строка {line_index:02d}, запуск {run:02d}/{NUM_RUNS}: {answer}")

        # Подсчёт частоты каждого варианта ответа
        counter = Counter(votes)
        # Наиболее частый ответ и число его появлений
        winner, count = counter.most_common(1)[0]
        # Итоговый вывод по строке: текст, победитель и распределение голосов
        print(
            # Первая часть сообщения: номер строки, текст и итоговый ответ
            f"step_6 [строка {line_index:02d}]: \"{line_text}\" -> {winner} "
            # Вторая часть: словарь голосов и доля победителя
            f"(голоса: {dict(counter)}, победитель {count}/{NUM_RUNS})"
        )
        # Возврат победившего ответа и счётчика голосов
        return winner, counter

    # Шаг 7: классификация всех строк входного файла
    def step_7_classify_all(lines: list[str]) -> list[tuple[int, str, str, Counter[str]]]:
        # Документация вложенной функции шага 7
        """Классифицировать все строки."""
        # Аккумулятор результатов: (номер, текст, YES/NO, голоса)
        results: list[tuple[int, str, str, Counter[str]]] = []
        # Перебор строк с нумерацией с 1
        for index, line in enumerate(lines, start=1):
            # Majority vote для текущей строки
            label, votes = step_6_majority_vote(line, index)
            # Сохранение записи в общий список результатов
            results.append((index, line, label, votes))
        # Сводка всех ответов в одну строку для лога
        summary = ", ".join(f"{idx}:{label}" for idx, _, label, _ in results)
        # Вывод итога классификации всех строк
        print(f"step_7: классификация завершена — {summary}")
        # Возврат полного списка результатов
        return results

    # Шаг 8: запись YES/NO в каталог result
    def step_8_save_results(
        # Каталог назначения для файлов результатов
        output_dir: Path,
        # Список результатов классификации
        results: list[tuple[int, str, str, Counter[str]]],
    ) -> list[Path]:
        # Документация вложенной функции шага 8
        """Сохранить YES/NO для каждой строки в каталог result."""
        # Список путей ко всем созданным файлам
        saved_paths: list[Path] = []

        # Путь к сводному файлу с ответами по одному на строку
        summary_path = output_dir / "results.txt"
        # Извлечение только меток YES/NO в порядке строк
        summary_lines = [label for _, _, label, _ in results]
        # Запись сводного файла: по одному ответу на строку
        summary_path.write_text("\n".join(summary_lines) + "\n", encoding="utf-8")
        # Регистрация пути сводного файла
        saved_paths.append(summary_path)

        # Путь к детализированному отчёту с текстом и голосами
        detailed_path = output_dir / "results_detailed.txt"
        # Формирование строк табличного детального отчёта
        detailed_lines = [
            # Строка отчёта: номер, ответ, текст, распределение голосов
            f"{index:02d}\t{label}\t{line}\tvotes={dict(votes)}"
            # Генерация строк для каждой записи results
            for index, line, label, votes in results
        ]
        # Запись детализированного отчёта на диск
        detailed_path.write_text("\n".join(detailed_lines) + "\n", encoding="utf-8")
        # Регистрация пути детального отчёта
        saved_paths.append(detailed_path)

        # Создание отдельного файла для каждой строки входных данных
        for index, line, label, votes in results:
            # Имя файла с нулевым дополнением номера строки
            line_path = output_dir / f"line_{index:02d}.txt"
            # Запись подробностей по одной строке в отдельный файл
            line_path.write_text(
                # Номер строки во входном файле
                f"line={index}\n"
                # Исходный текст строки
                f"text={line}\n"
                # Итоговый ответ majority vote
                f"answer={label}\n"
                # Распределение голосов YES/NO
                f"votes={dict(votes)}\n"
                # Число выполненных запусков модели
                f"runs={NUM_RUNS}\n",
                # Кодировка UTF-8 для корректного сохранения кириллицы
                encoding="utf-8",
            )
            # Добавление пути файла строки в список сохранённых
            saved_paths.append(line_path)

        # Сообщение о количестве записанных файлов и каталоге
        print(f"step_8: сохранено {len(saved_paths)} файлов в {output_dir}")
        # Возврат списка путей всех созданных файлов
        return saved_paths

    # Вызов шага 1: загрузка строк из test_b2.txt
    lines = step_1_load_lines()
    # Вызов шага 2: подготовка каталога result
    output_dir = step_2_prepare_dirs()
    # Вызов шага 7: классификация всех строк через Ollama
    results = step_7_classify_all(lines)
    # Вызов шага 8: сохранение результатов на диск
    saved_paths = step_8_save_results(output_dir, results)

    # Финальное сообщение об успешном завершении пайплайна
    print("main: готово")
    # Вывод имени использованной модели
    print(f"  модель: {MODEL_NAME}")
    # Вывод числа запусков на каждую строку
    print(f"  запусков на строку: {NUM_RUNS}")
    # Вывод пути к основному сводному файлу результатов
    print(f"  итоговый файл: {saved_paths[0]}")


# Точка входа при запуске скрипта как программы
if __name__ == "__main__":
    # Запуск главной функции main()
    main()
